"""Small CPU/GPU checkpoint inspection CLI; NOT the full Colab evaluation protocol.

Uses the preserved, unrefactored PtrNet1 model. The prediction procedure mirrors
predict_one_instance from the corrected v1.2 evaluation notebook, with a device
parameter and a simple fixed instance generator. Full paper results are archived,
not regenerated by this script.
"""
from pathlib import Path
from types import SimpleNamespace
import argparse
import sys

import numpy as np
import torch

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / 'code_snapshot'))
sys.path.insert(0, str(REPO / 'src'))
from actor import PtrNet1  # noqa: E402
from tsp_drl.algorithms.reference_baselines import tour_length_np  # noqa: E402

DEFAULT_CHECKPOINT = REPO / 'models' / 'seed_20261013' / 'train20_1013_17_14_step12999_act.pt'
MODEL_ARGS = dict(embed=128, hidden=128, init_min=-0.08, init_max=0.08,
                  clip_logits=10, softmax_T=1.0, n_glimpse=1)


def predict(coords, checkpoint, decode='greedy', sample_count=512, seed=8302046, device='cpu'):
    if decode not in ('greedy', 'best-of-512'):
        raise ValueError('decode must be greedy or best-of-512')
    if decode == 'best-of-512' and sample_count <= 0:
        raise ValueError('sample_count must be positive')
    selector = 'greedy' if decode == 'greedy' else 'sampling'
    batch_size = 1 if decode == 'greedy' else int(sample_count)
    torch.manual_seed(int(seed))
    if device.startswith('cuda'):
        torch.cuda.manual_seed_all(int(seed))
    model = PtrNet1(SimpleNamespace(**MODEL_ARGS, decode_type=selector)).to(device)
    try:
        state = torch.load(checkpoint, map_location=device, weights_only=True)
    except TypeError:
        state = torch.load(checkpoint, map_location=device)
    model.load_state_dict(state)
    model.eval()
    x = torch.as_tensor(coords, dtype=torch.float32, device=device).unsqueeze(0)
    x = x.repeat(batch_size, 1, 1)
    with torch.inference_mode():
        tours, _ = model(x, torch.device(device))
        ordered = torch.gather(x, 1, tours.long().unsqueeze(-1).expand(-1, -1, 2))
        lengths = (torch.linalg.vector_norm(ordered[:, 1:] - ordered[:, :-1], dim=-1).sum(dim=1)
                   + torch.linalg.vector_norm(ordered[:, 0] - ordered[:, -1], dim=-1))
        index = torch.argmin(lengths)
        tour = tours[index].cpu().numpy().astype(np.int64)
        torch_length = float(lengths[index].item())
    if sorted(tour.tolist()) != list(range(len(coords))):
        raise AssertionError('Invalid permutation from actor')
    np_length = tour_length_np(coords, tour)
    if abs(np_length - torch_length) > 5e-5:
        raise AssertionError('Tour-cost disagreement between PyTorch and NumPy')
    return tour, np_length


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--n',type=int,default=20,choices=(20,50,100))
    p.add_argument('--decode',choices=('greedy','best-of-512'),default='greedy')
    p.add_argument('--sample-count',type=int,default=512,
                   help='Experimental default 512; smaller values are smoke tests only')
    p.add_argument('--seed',type=int,default=8302026)
    p.add_argument('--checkpoint',type=Path,default=DEFAULT_CHECKPOINT)
    p.add_argument('--device',default='cpu')
    args=p.parse_args()
    rng=np.random.default_rng(args.seed + args.n)
    coords=rng.random((args.n, 2))
    tour, cost=predict(coords,args.checkpoint,args.decode,args.sample_count,
                      args.seed + args.n,args.device)
    print(f'n={args.n}, decode={args.decode}, sample_count={1 if args.decode == "greedy" else args.sample_count}, cost={cost:.8f}')
    print('tour:',','.join(str(i) for i in tour))


if __name__=='__main__':
    main()
